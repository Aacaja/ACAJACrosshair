/// ADS 模式名文案
pub fn ads_mode_name(lang: Lang, mode: AdsMode) -> &'static str {
    let key = match mode {
        AdsMode::Off => "ads_off",
        AdsMode::HoldHide => "ads_hold_hide",
        AdsMode::Toggle => "ads_toggle",
        AdsMode::HoldShow => "ads_hold_show",
    };
    t(lang, key)
}